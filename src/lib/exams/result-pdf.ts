/**
 * Result PDFs — A4 portrait class result sheet + individual student card.
 */

import { jsPDF } from 'jspdf'
import autoTable from 'jspdf-autotable'
import type { ExamDTO } from '@/lib/exams/types'
import { formatDateLong } from '@/lib/exams/format-helpers'

interface StudentResult {
  studentId: string
  name: string
  rollNo: string | null
  className: string
  subjects: Array<{ subjectName: string; maxMarks: number; obtained: number | null; percentage: number; grade: string; passed: boolean }>
  totalObtained: number
  totalMax: number
  percentage: number
  grade: string
  passed: boolean
  rank: number | null
}

/** Generate A4 portrait class result sheet. */
export function generateClassResultPDF(exam: ExamDTO, className: string, results: StudentResult[]): void {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' })
  const pageW = doc.internal.pageSize.getWidth()

  // Header
  doc.setFontSize(14); doc.setFont('helvetica', 'bold')
  doc.text('Demo School of Scholario', pageW / 2, 15, { align: 'center' })
  doc.setFontSize(10)
  doc.text(exam.name, pageW / 2, 21, { align: 'center' })
  doc.setFontSize(8); doc.setFont('helvetica', 'normal')
  doc.text(`Academic Session ${exam.session ?? ''}`, pageW / 2, 26, { align: 'center' })
  doc.setFontSize(9); doc.setFont('helvetica', 'bold')
  doc.text(`Class Result Sheet — ${className}`, pageW / 2, 32, { align: 'center' })

  // Build table: Roll | Name | subj1 | subj2 | ... | Total | % | Grade | Result
  const subjects = results[0]?.subjects ?? []
  const head = [['Roll', 'Student', ...subjects.map((s) => s.subjectName.substring(0, 8)), 'Total', '%', 'Grade', 'Result']]

  const body = results.map((r) => {
    const subjMarks = r.subjects.map((s) => s.obtained !== null ? String(s.obtained) : '—')
    return [r.rollNo ?? '', r.name, ...subjMarks, `${r.totalObtained}/${r.totalMax}`, `${r.percentage}%`, r.grade, r.passed ? 'PASS' : 'FAIL']
  })

  autoTable(doc, {
    head,
    body,
    startY: 36,
    styles: { fontSize: 6, cellPadding: 1 },
    headStyles: { fillColor: [15, 118, 110], textColor: 255, fontSize: 6 },
    alternateRowStyles: { fillColor: [245, 250, 249] },
    didDrawPage: (data) => {
      // Page number
      const pageH = doc.internal.pageSize.getHeight()
      doc.setFontSize(6); doc.setFont('helvetica', 'normal')
      doc.text(`Page ${data.pageNumber}`, pageW / 2, pageH - 4, { align: 'center' })
    },
  })

  // Footer
  const pageH = doc.internal.pageSize.getHeight()
  doc.setFontSize(6)
  doc.text(`Generated by Scholario-OS · ${new Date().toLocaleDateString()}`, pageW / 2, pageH - 8, { align: 'center' })

  doc.save(`${exam.name.replace(/\s+/g, '-')}-${className.replace(/\s+/g, '-')}-result.pdf`)
}

/** Generate A4 portrait individual student result card. */
export function generateStudentResultPDF(exam: ExamDTO, result: StudentResult): void {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' })
  const pageW = doc.internal.pageSize.getWidth()

  // Header
  doc.setFontSize(14); doc.setFont('helvetica', 'bold')
  doc.text('Demo School of Scholario', pageW / 2, 20, { align: 'center' })
  doc.setFontSize(10)
  doc.text(exam.name, pageW / 2, 27, { align: 'center' })
  doc.setFontSize(8); doc.setFont('helvetica', 'normal')
  doc.text(`Academic Session ${exam.session ?? ''}`, pageW / 2, 32, { align: 'center' })

  // Student info
  doc.setFontSize(10); doc.setFont('helvetica', 'bold')
  doc.text(`${result.name}`, pageW / 2, 42, { align: 'center' })
  doc.setFontSize(8); doc.setFont('helvetica', 'normal')
  doc.text(`Roll No: ${result.rollNo ?? ''}  ·  Class: ${result.className}`, pageW / 2, 47, { align: 'center' })

  // Subject table
  const head = [['Subject', 'Max', 'Obtained', '%', 'Grade', 'Result']]
  const body = result.subjects.map((s) => [
    s.subjectName, String(s.maxMarks), s.obtained !== null ? String(s.obtained) : '—',
    `${s.percentage}%`, s.grade, s.passed ? 'PASS' : 'FAIL',
  ])

  autoTable(doc, {
    head,
    body,
    startY: 52,
    styles: { fontSize: 9, cellPadding: 2 },
    headStyles: { fillColor: [15, 118, 110], textColor: 255 },
    alternateRowStyles: { fillColor: [245, 250, 249] },
  })

  // Summary
  const finalY = (doc as any).lastAutoTable?.finalY ?? 80
  doc.setFontSize(10); doc.setFont('helvetica', 'bold')
  doc.text(`Total: ${result.totalObtained} / ${result.totalMax}`, 14, finalY + 10)
  doc.text(`Percentage: ${result.percentage}%`, 14, finalY + 16)
  doc.text(`Grade: ${result.grade}`, 14, finalY + 22)
  doc.text(`Result: ${result.passed ? 'PASS' : 'FAIL'}`, 14, finalY + 28)
  if (result.rank) doc.text(`Rank: ${result.rank}`, 14, finalY + 34)

  // Signature area
  const pageH = doc.internal.pageSize.getHeight()
  doc.setFontSize(8); doc.setFont('helvetica', 'normal')
  doc.text('Class Teacher', 30, pageH - 20)
  doc.text('Principal', pageW - 40, pageH - 20)
  doc.text(`Generated by Scholario-OS · ${new Date().toLocaleDateString()}`, pageW / 2, pageH - 8, { align: 'center' })

  doc.save(`${result.name.replace(/\s+/g, '-')}-result.pdf`)
}

/** Export marks as CSV (re-importable). */
export function exportMarksCSV(exam: ExamDTO, className: string, subjectName: string, marks: Array<{ studentId: string; studentName: string; rollNo: string | null; marksObtained: number | null; status: string }>): void {
  const rows = [
    ['examId', 'classId', 'studentId', 'rollNumber', 'studentName', 'subjectName', 'marksObtained', 'status'],
    ...marks.map((m) => [exam.id, className, m.studentId, m.rollNo ?? '', m.studentName, subjectName, m.marksObtained ?? '', m.status]),
  ]
  const csv = rows.map((r) => r.map((c) => `"${c}"`).join(',')).join('\n')
  const blob = new Blob([csv], { type: 'text/csv' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = `${exam.name.replace(/\s+/g, '-')}-${className.replace(/\s+/g, '-')}-${subjectName.replace(/\s+/g, '-')}-marks.csv`
  a.click()
  URL.revokeObjectURL(url)
}
